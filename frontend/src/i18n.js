/** "5 min ago" style relative time. */
export function timeAgo(iso, t) {
  const mins = Math.round((Date.now() - Date.parse(iso)) / 60000);
  if (mins < 1) return t.just_now;
  if (mins < 60) return t.ago(mins, t.units.m);
  if (mins < 60 * 24) return t.ago(Math.round(mins / 60), t.units.h);
  return t.ago(Math.round(mins / 1440), t.units.d);
}

