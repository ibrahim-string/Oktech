export function formatWhen(iso, lang) {
  return new Intl.DateTimeFormat(lang === "ja" ? "ja-JP" : "en-GB", {
    weekday: "short",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    timeZone: "Asia/Tokyo",
  }).format(new Date(iso));
}

