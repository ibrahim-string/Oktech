/** UI language for a user: Japanese UI for ja, English for everyone else. */
export const uiLang = (preferred) => (preferred === "ja" ? "ja" : "en");

export function formatWhen(iso, lang) {
  return new Intl.DateTimeFormat(lang === "ja" ? "ja-JP" : "en-GB", {
    weekday: "short",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    timeZone: "Asia/Tokyo",
  }).format(new Date(iso));
}

export const listLangs = (codes, t) => codes.map((c) => t.languages[c] ?? c).join(", ");
