import pg from "pg";

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL is not set. Add your Supabase connection string to backend/.env (see .env.example).");
  process.exit(1);
}

const url = process.env.DATABASE_URL;
const isLocal = /@(localhost|127\.0\.0\.1)[:/]/.test(url);

export const pool = new pg.Pool({
  connectionString: url,
  // Supabase requires TLS; its certificate chain isn't in Node's default store.
  ssl: isLocal ? false : { rejectUnauthorized: false },
  max: Number(process.env.DB_POOL_SIZE ?? 5),
});

/** Run a query and return all rows. */
export async function query(sql, params = []) {
  const { rows } = await pool.query(sql, params);
  return rows;
}

/** Run a query and return the first row (or undefined). */
export async function one(sql, params = []) {
  return (await query(sql, params))[0];
}

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL,
  bio             text NOT NULL DEFAULT '',
  area            text NOT NULL DEFAULT '',            -- e.g. Kobe, Osaka, Kyoto
  is_local        boolean NOT NULL DEFAULT false,      -- true = local Japanese resident
  preferred_lang  text NOT NULL DEFAULT 'en',          -- language the UI/feed is shown in
  speaks          jsonb NOT NULL DEFAULT '[]',         -- languages they can share/teach
  learning        jsonb NOT NULL DEFAULT '[]',         -- languages they want to practice
  interests       jsonb NOT NULL DEFAULT '[]',         -- free-form tags
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hangouts (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host_id           integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title             text NOT NULL,
  description       text NOT NULL DEFAULT '',
  category          text NOT NULL DEFAULT 'language_exchange',
  languages         jsonb NOT NULL DEFAULT '["ja","en"]', -- languages used at the meetup
  area              text NOT NULL,
  place_name        text NOT NULL,                        -- public place: cafe, community space...
  starts_at         timestamptz NOT NULL,
  max_participants  integer NOT NULL DEFAULT 4,
  status            text NOT NULL DEFAULT 'open',         -- open | cancelled | done
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hangout_participants (
  hangout_id  integer NOT NULL REFERENCES hangouts(id) ON DELETE CASCADE,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  joined_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (hangout_id, user_id)
);

CREATE TABLE IF NOT EXISTS messages (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hangout_id  integer NOT NULL REFERENCES hangouts(id) ON DELETE CASCADE,
  sender_id   integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS translations (
  source_hash  text NOT NULL,
  target_lang  text NOT NULL,
  translated   text NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source_hash, target_lang)
);

-- Anonymous sessions: the browser holds a random token; we store only its hash.
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_hash text UNIQUE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_seen timestamptz NOT NULL DEFAULT now();

-- 1:1 chats: random matches ("random") and replies to aid posts ("aid").
CREATE TABLE IF NOT EXISTS conversations (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         text NOT NULL,                       -- random | aid
  topic        integer,                             -- icebreaker index (random chats)
  aid_post_id  integer,                             -- set for aid chats
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS conversation_members (
  conversation_id  integer NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id          integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  left_at          timestamptz,
  PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE IF NOT EXISTS conversation_messages (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id  integer NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id        integer REFERENCES users(id) ON DELETE SET NULL,
  kind             text NOT NULL DEFAULT 'text',     -- text | left | topic (system events)
  body             text NOT NULL DEFAULT '',
  created_at       timestamptz NOT NULL DEFAULT now()
);

-- People waiting for a random match. Rows expire if the client stops polling.
CREATE TABLE IF NOT EXISTS match_queue (
  user_id                  integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  matched_conversation_id  integer REFERENCES conversations(id) ON DELETE SET NULL,
  created_at               timestamptz NOT NULL DEFAULT now(),
  last_seen                timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS blocks (
  blocker_id  integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  blocked_id  integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (blocker_id, blocked_id)
);

CREATE TABLE IF NOT EXISTS reports (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id      integer REFERENCES users(id) ON DELETE SET NULL,
  reported_id      integer REFERENCES users(id) ON DELETE SET NULL,
  conversation_id  integer REFERENCES conversations(id) ON DELETE SET NULL,
  reason           text NOT NULL DEFAULT '',
  created_at       timestamptz NOT NULL DEFAULT now()
);

-- Mutual aid board for disasters: "need" help or "offer" help.
CREATE TABLE IF NOT EXISTS aid_posts (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind        text NOT NULL,                        -- need | offer
  category    text NOT NULL DEFAULT 'other',
  title       text NOT NULL,
  body        text NOT NULL DEFAULT '',
  area        text NOT NULL,
  status      text NOT NULL DEFAULT 'open',         -- open | resolved
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- Latest "I'm safe" / "I need help" check-in per person.
CREATE TABLE IF NOT EXISTS safety_checkins (
  user_id     integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  status      text NOT NULL,                        -- safe | need_help
  area        text NOT NULL DEFAULT '',
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Emergency alerts raised by an organizer (earthquake, flood, typhoon...).
CREATE TABLE IF NOT EXISTS alerts (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        text NOT NULL,                        -- earthquake | flood | typhoon | tsunami | other
  area        text,                                 -- null = all of Kansai
  title       text NOT NULL,
  message     text NOT NULL DEFAULT '',
  active      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_hangouts_starts ON hangouts(starts_at);
CREATE INDEX IF NOT EXISTS idx_conv_members_user ON conversation_members(user_id);
CREATE INDEX IF NOT EXISTS idx_conv_messages_conv ON conversation_messages(conversation_id, id);
CREATE INDEX IF NOT EXISTS idx_conv_messages_sender ON conversation_messages(sender_id);
CREATE INDEX IF NOT EXISTS idx_blocks_blocked ON blocks(blocked_id);
CREATE INDEX IF NOT EXISTS idx_reports_reporter ON reports(reporter_id);
CREATE INDEX IF NOT EXISTS idx_reports_reported ON reports(reported_id);
CREATE INDEX IF NOT EXISTS idx_reports_conv ON reports(conversation_id);
CREATE INDEX IF NOT EXISTS idx_match_queue_conv ON match_queue(matched_conversation_id);
CREATE INDEX IF NOT EXISTS idx_aid_posts_created ON aid_posts(created_at);
CREATE INDEX IF NOT EXISTS idx_aid_posts_user ON aid_posts(user_id);
CREATE INDEX IF NOT EXISTS idx_hangouts_host ON hangouts(host_id);
CREATE INDEX IF NOT EXISTS idx_participants_user ON hangout_participants(user_id);
CREATE INDEX IF NOT EXISTS idx_messages_hangout ON messages(hangout_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_sender ON messages(sender_id);

-- The API is the only client. RLS with no policies blocks Supabase's public Data API
-- (anon/authenticated keys), while the postgres role used by this server bypasses it.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE hangouts ENABLE ROW LEVEL SECURITY;
ALTER TABLE hangout_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE translations ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversation_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversation_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE match_queue ENABLE ROW LEVEL SECURITY;
ALTER TABLE blocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE aid_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE safety_checkins ENABLE ROW LEVEL SECURITY;
ALTER TABLE alerts ENABLE ROW LEVEL SECURITY;
`;

/** Create tables if they don't exist. Safe to run on every boot. */
export async function migrate() {
  await pool.query(SCHEMA);
}

/** Run `fn(client)` in a transaction; commits on success, rolls back on error. */
export async function withTransaction(fn) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}
